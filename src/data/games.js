/**
 * 获取所有游戏
 * @returns {Array} 游戏列表
 */
export function getAllGames() {
  return games;
}

/**
 * 根据ID获取游戏
 * @param {string} id - 游戏ID
 * @returns {Object|undefined} 游戏对象或undefined
 */
export function getGameById(id) {
  return games.find(game => game.id === id);
}

/**
 * 根据分类获取游戏
 * @param {string} category - 游戏分类
 * @returns {Array} 游戏列表
 */
export function getGamesByCategory(category) {
  return games.filter(game => game.category === category);
}

/**
 * 根据标签获取游戏
 * @param {string} tag - 游戏标签
 * @returns {Array} 游戏列表
 */
export function getGamesByTag(tag) {
  return games.filter(game => game.tags && game.tags.includes(tag));
}

/**
 * 搜索游戏
 * @param {string} query - 搜索关键词
 * @returns {Array} 游戏列表
 */
export function searchGames(query) {
  const lowerQuery = query.toLowerCase();
  return games.filter(game => 
    game.title.toLowerCase().includes(lowerQuery) || 
    game.description.toLowerCase().includes(lowerQuery) ||
    (game.tags && game.tags.some(tag => tag.toLowerCase().includes(lowerQuery)))
  );
}

/**
 * 设置游戏数据
 * 用于批量更新游戏数据
 * @param {Array} newGames - 新的游戏数据
 */
export function setGamesData(newGames) {
  if (Array.isArray(newGames)) {
    games = newGames;
    console.log(`游戏数据已更新，共 ${games.length} 个游戏`);
  } else {
    console.error('无效的游戏数据格式，必须是数组');
  }
}

export default {
  games,
  getAllGames,
  getGameById,
  getGamesByCategory,
  getGamesByTag,
  searchGames,
  setGamesData
}; 